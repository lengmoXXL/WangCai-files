  await keyboard.press('Enter');
  assert.deepEqual(await names(from), [...files].reverse());
  await keyboard.press('=');
  await page.getByText('没有目录变更', { exact: true }).waitFor();
  await keyboard.type(':sort');
  await keyboard.press('Enter');
  assert.deepEqual(await names(from), files);
  await keyboard.type('ggdd.');
  await entry(root, 'target/').click();
  await emptyDirectory(page).waitFor();
  await keyboard.press('P');
  await keyboard.press('=');
  await review.getByText('移动 source/b.md → target/b.md', { exact: true }).waitFor();
