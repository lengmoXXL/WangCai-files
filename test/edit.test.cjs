  await keyboard.press('Enter');
  await entry(root, 'alternate/').click();
  await emptyDirectory(page).waitFor();
  await keyboard.press('i');
  await keyboard.type('placeholder.md');
  await keyboard.press('Escape');
  await keyboard.press('V');
  await keyboard.type('"ap');
  await entry(columnOf(page, alternate), 'note.md').waitFor();
  await keyboard.press('=');
  await review.getByText('复制 source/note.md → alternate/note.md', { exact: true }).waitFor();
  await keyboard.press('Enter');
