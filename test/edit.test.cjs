test('directory edits stay in the Vim buffer until the reviewed changes are applied', { timeout: 180000 }, () => withWindow('wangcai-edit', lists, async ({ home, page, errors }) => {
  writeFileSync(join(home, 'alpha.md'), 'alpha');
  writeFileSync(join(home, 'beta.md'), 'beta');
  await openFilesWorkspace(page);
  const directory = columnOf(page, home);
  await entry(directory, 'alpha.md').waitFor();

  const { keyboard } = page;
  const buffer = directory.locator('.cm-content');
  await keyboard.press('/');
  await searchField(page).fill('alpha.md');
  await keyboard.press('Enter');
  await keyboard.press('i');
  await keyboard.type('draft-');
  await keyboard.press('Escape');
  await entry(directory, 'draft-alpha.md').waitFor();
  assert.equal(readFileSync(join(home, 'alpha.md'), 'utf8'), 'alpha');
  await keyboard.press('u');
  await entry(directory, 'alpha.md').waitFor();
  await keyboard.type(':%s/\\.md$/.txt/');
  await keyboard.press('Enter');
  await buffer.getByText('beta.txt', { exact: true }).waitFor();
  await keyboard.press('G');
  await keyboard.press('o');
  await keyboard.type('-fresh note.txt');
  await keyboard.press('Escape');
  await keyboard.press('O');
  await keyboard.type('new-dir/');
  await keyboard.press('Escape');

  await keyboard.press('H');
  await directory.waitFor({ state: 'detached' });
  await entry(columnOf(page, dirname(home)), `${basename(home)}/`).click();
  await entry(directory, 'alpha.txt').waitFor();

  const review = page.getByRole('dialog', { name: '文件变更预览' });
  await keyboard.press('/');
  await searchField(page).fill('alpha.txt');
  await keyboard.press('Enter');
  await keyboard.type('dd');
  await keyboard.press('=');
  await review.getByText('删除 alpha.md', { exact: true }).waitFor();
  await keyboard.press('Escape');
  await review.waitFor({ state: 'detached' });
  await keyboard.press('u');
  await keyboard.press('=');
  for (const operation of ['重命名 alpha.md → alpha.txt', '重命名 beta.md → beta.txt', '新建 -fresh note.txt', '新建 new-dir/']) {
    await review.getByText(operation, { exact: true }).waitFor();
  }
  assert.equal(await review.getByRole('listitem').count(), 4);
  assert.equal(readFileSync(join(home, 'alpha.md'), 'utf8'), 'alpha');
  assert.ok(!existsSync(join(home, 'new-dir')));
  await keyboard.press('Escape');
  await buffer.waitFor();

  writeFileSync(join(home, 'beta.txt'), 'from outside the draft');
  await keyboard.press('=');
  await review.getByRole('button', { name: '应用变更' }).click();
  await page.getByText('目录中已有同名条目：beta.txt').waitFor();
  assert.equal(readFileSync(join(home, 'beta.txt'), 'utf8'), 'from outside the draft');
  assert.ok(!existsSync(join(home, 'alpha.txt')));
  unlinkSync(join(home, 'beta.txt'));

  await keyboard.press('=');
  await review.getByRole('button', { name: '应用变更' }).click();
  await entry(directory, 'alpha.txt').waitFor();
  assert.equal(readFileSync(join(home, 'alpha.txt'), 'utf8'), 'alpha');
  assert.equal(readFileSync(join(home, 'beta.txt'), 'utf8'), 'beta');
  assert.ok(!existsSync(join(home, 'alpha.md')));
  assert.equal(statSync(join(home, '-fresh note.txt')).size, 0);
  assert.ok(statSync(join(home, 'new-dir')).isDirectory());

  await entry(directory, 'new-dir/').click();
  await emptyDirectory(page).waitFor();
  await keyboard.press('i');
  await keyboard.type('created.txt');
  await keyboard.press('Escape');
  await keyboard.press('o');
  await keyboard.insertText('a'.repeat(256));
  await keyboard.press('Escape');
  await keyboard.press('=');
  await review.getByRole('button', { name: '应用变更' }).click();
  await page.getByRole('status').filter({ hasText: /^已应用 1 项/ }).waitFor();
  assert.equal(statSync(join(home, 'new-dir/created.txt')).size, 0);

  await keyboard.type('Gdd');
  await keyboard.press('=');
  await page.getByText('没有目录变更', { exact: true }).waitFor();
  await keyboard.press('o');
  await keyboard.type('try-again.txt');
  await keyboard.press('Escape');
  await keyboard.press('=');
  assert.equal(await review.getByRole('listitem').count(), 1);
  await keyboard.press('Enter');
  await entry(columnOf(page, join(home, 'new-dir')), 'try-again.txt').waitFor();
  assert.deepEqual(errors, []);
}));

test('nested paths create shared directories and preview moves for keyboard confirmation', { timeout: 180000 }, () => withWindow('wangcai-nested-edit', lists, async ({ home, page, errors }) => {
  writeFileSync(join(home, 'notes.md'), 'move me');
  await openFilesWorkspace(page);
  const directory = columnOf(page, home);
  await entry(directory, 'notes.md').waitFor();
  const { keyboard } = page;
  await keyboard.press('/');
  await searchField(page).fill('notes.md');
  await keyboard.press('Enter');
  await keyboard.type('cc');
  await keyboard.type('abc/notes.md');
  await keyboard.press('Escape');
  for (const path of ['abc/123.md', 'abc/456.md', 'abc/docs/readme.md', 'abc/docs/']) {
    await keyboard.press('o');
    await keyboard.type(path);
    await keyboard.press('Escape');
  }

  const review = page.getByRole('dialog', { name: '文件变更预览' });
  await keyboard.press('=');
  await review.getByText('移动 notes.md → abc/notes.md', { exact: true }).waitFor();
  await review.getByText('新建 abc/123.md', { exact: true }).waitFor();
  await review.getByText('新建 abc/456.md', { exact: true }).waitFor();
  await keyboard.press('n');
  await review.waitFor({ state: 'detached' });
  assert.ok(!existsSync(join(home, 'abc')));

  writeFileSync(join(home, 'abc'), 'blocks the parent path');
  await keyboard.press('=');
  await review.waitFor();
  await keyboard.press('y');
  await page.getByRole('status').filter({ hasText: '上级路径被文件占用：abc' }).waitFor();
  assert.equal(readFileSync(join(home, 'notes.md'), 'utf8'), 'move me');
  unlinkSync(join(home, 'abc'));

  await keyboard.press('=');
  await review.waitFor();
  await keyboard.press('Enter');
  await entry(directory, 'abc/').waitFor();
  assert.ok(!existsSync(join(home, 'notes.md')));
  assert.equal(readFileSync(join(home, 'abc/notes.md'), 'utf8'), 'move me');
  for (const path of ['abc/123.md', 'abc/456.md', 'abc/docs/readme.md']) assert.equal(statSync(join(home, path)).size, 0);
  assert.deepEqual(errors, []);
}));

test('a Vim linewise cut and paste into the parent previews and applies moves', { timeout: 180000 }, () => withWindow('wangcai-parent-edit', lists, async ({ home, page, errors }) => {
  const child = join(home, 'sub');
  mkdirSync(child);
  writeFileSync(join(child, 'alpha.md'), 'alpha contents');
  writeFileSync(join(child, 'beta.md'), 'beta contents');
  await openFilesWorkspace(page);
  const parent = columnOf(page, home);
  const source = columnOf(page, child);
  await entry(parent, 'sub/').click();
  await entry(source, 'alpha.md').waitFor();

  const { keyboard } = page;
  await keyboard.type('ggVjy');
  await keyboard.type('ggVj"_d');
  await entry(source, 'alpha.md').waitFor({ state: 'detached' });
  await keyboard.press('H');
  await source.waitFor({ state: 'detached' });
  await keyboard.press('P');
  await entry(parent, 'alpha.md').waitFor();
  await keyboard.type(':%s/^beta.md$/moved-beta.md/');
  await keyboard.press('Enter');

  const review = page.getByRole('dialog', { name: '文件变更预览' });
  await keyboard.press('=');
  await review.getByText('移动 sub/alpha.md → alpha.md', { exact: true }).waitFor();
  await review.getByText('移动 sub/beta.md → moved-beta.md', { exact: true }).waitFor();
  assert.ok(!existsSync(join(home, 'alpha.md')));
  assert.ok(existsSync(join(child, 'alpha.md')));
  await keyboard.press('n');
  await entry(parent, 'sub/').click();
  await source.waitFor();
  await keyboard.press('=');
  await review.getByText('移动 sub/beta.md → moved-beta.md', { exact: true }).waitFor();
  await keyboard.press('y');
  await review.waitFor({ state: 'detached' });
  assert.equal(readFileSync(join(home, 'alpha.md'), 'utf8'), 'alpha contents');
  assert.equal(readFileSync(join(home, 'moved-beta.md'), 'utf8'), 'beta contents');
  assert.ok(!existsSync(join(child, 'alpha.md')) && !existsSync(join(child, 'beta.md')));
  await emptyDirectory(page).waitFor();

  writeFileSync(join(child, 'single.md'), 'single contents');
  await entry(source, 'single.md').waitFor();
  await keyboard.type('dd');
  await keyboard.press('H');
  await source.waitFor({ state: 'detached' });
  await keyboard.press('p');
  await entry(parent, 'single.md').waitFor();
  await keyboard.press('=');
  await review.getByText('移动 sub/single.md → single.md', { exact: true }).waitFor();
  await keyboard.press('Enter');
  await review.waitFor({ state: 'detached' });
  assert.equal(readFileSync(join(home, 'single.md'), 'utf8'), 'single contents');
  assert.ok(!existsSync(join(child, 'single.md')));
  assert.deepEqual(errors, []);
}));

